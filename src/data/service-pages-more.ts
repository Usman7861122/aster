import type { ServicePage } from "./service-pages";

type Pair = [string, string];
interface Cfg {
  slug: string;
  title: string;
  metaTitle?: string;
  eyebrow: string;
  lede: string;
  hero: string; a: string; b: string;
  heroPos?: string;
  heroAlt: string; aAlt: string; bAlt: string;
  intro: { eyebrow: string; title: string; lead: string; text: string; cta: string };
  steps: { eyebrow: string; title: string; items: Pair[] };
  detail: { eyebrow: string; title: string; note?: string; items: Pair[] };
  faqs: Pair[];
  related: string[];
  closing: Pair;
}

const img = (n: string) => `/images/${n}.jpg`;
const rows = (p: Pair[]) => p.map(([title, text]) => ({ title, text }));

function mk(c: Cfg): ServicePage {
  return {
    slug: c.slug,
    title: c.title,
    metaTitle: c.metaTitle ?? `${c.title.replace(" in Manhattan", "")} on the Upper West Side | Aster OB/GYN`,
    eyebrow: c.eyebrow,
    lede: c.lede,
    heroImg: img(c.hero),
    heroAlt: c.heroAlt,
    heroPos: c.heroPos,
    intro: { ...c.intro, img: img(c.a), imgAlt: c.aAlt },
    steps: { ...c.steps, items: rows(c.steps.items) },
    detail: { ...c.detail, img: img(c.b), imgAlt: c.bAlt, items: rows(c.detail.items) },
    faqs: c.faqs.map(([q, a]) => ({ q, a })),
    related: c.related,
    closing: { title: c.closing[0], text: c.closing[1] },
  };
}

